import { useApi } from '../api/context';
import type { AnalyticsName } from '../api/types';
import { PageHeader } from '../components/Layout';
import { Probe } from '../components/Probe';

const PANELS: { name: AnalyticsName; title: string }[] = [
  { name: 'backtest', title: 'Backtest' },
  { name: 'pricing', title: 'Pricing' },
  { name: 'solvency', title: 'Solvency' },
  { name: 'basis-risk', title: 'Basis risk' },
  { name: 'trigger', title: 'Trigger design' },
  { name: 'data-quality', title: 'Data quality' },
];

// K3 empty page. E1 adds the panels; each will show its provenance and "not computed" for nulls.
export function EvidencePage() {
  const api = useApi();
  return (
    <>
      <PageHeader
        title="Evidence"
        purpose="Backtest, pricing, solvency, basis-risk and data-quality panels, each with its provenance."
      />
      {PANELS.map((p) => (
        <section key={p.name} aria-label={p.title}>
          <h2>{p.title}</h2>
          <Probe
            what={`${p.title.toLowerCase()} artifact`}
            loadKey={`analytics:${p.name}`}
            load={() => api.analytics(p.name)}
            summary={(a) => `generated by ${a.provenance.code} at ${a.provenance.generated_at}`}
          />
        </section>
      ))}
    </>
  );
}
